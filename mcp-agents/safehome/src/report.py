"""Safety report generator — combines geocoding, FEMA, and NWS data into
a comprehensive property safety assessment.
"""

from __future__ import annotations

from src.geocoder import geocode, get_county_for_point
from src.disasters import (
    get_state_code,
    summarize_disasters_for_county,
)
from src.weather import (
    get_active_alerts,
    get_forecast,
    format_alerts,
    format_forecast,
)


def generate_safety_report(address: str) -> str:
    """Generate a complete property safety report for a US address.

    Combines:
    1. Geocoding (address -> lat/lon)
    2. FEMA disaster history for the county
    3. Active weather alerts
    4. 7-day forecast

    Returns a formatted Markdown string.
    """
    # Step 1: Geocode
    lat, lon, formatted_address = geocode(address)

    # Step 2: Get county
    county = get_county_for_point(lat, lon)

    # Step 3: FEMA disaster history
    # Extract state from formatted address or county info
    state_abbr = _extract_state(formatted_address, county)

    disaster_summary = ""
    if county and state_abbr:
        # Clean county name for matching
        county_clean = county.replace(" County", "").replace(" Parish", "")
        disaster_summary = summarize_disasters_for_county(state_abbr, county_clean)

    # Step 4: Active weather alerts
    alerts = get_active_alerts(lat, lon)
    alerts_formatted = format_alerts(alerts)

    # Step 5: Forecast
    forecast = get_forecast(lat, lon)
    forecast_formatted = format_forecast(forecast) if forecast else "Forecast unavailable."

    # Build the report
    severity_badge = _severity_badge(alerts)
    disaster_badge = _disaster_badge(disaster_summary)

    lines = [
        f"# 🏡 SafeHome Report — {formatted_address}",
        "",
        f"**Location**: {formatted_address}",
        f"**Coordinates**: {lat:.5f}, {lon:.5f}",
        f"**County**: {county or 'Unknown'}",
        f"**State**: {state_abbr or 'Unknown'}",
        "",
        "---",
        "",
        "## ⚠️ Safety Overview",
        "",
        severity_badge,
        disaster_badge,
        "",
        "---",
        "",
        "## 🌊 FEMA Disaster History",
        "",
        disaster_summary or "Could not retrieve FEMA data for this location.",
        "",
        "---",
        "",
        "## 🌀 Active Weather Alerts",
        "",
        alerts_formatted,
        "",
        "---",
        "",
        "## 🌤️ 7-Day Forecast",
        "",
        forecast_formatted,
        "",
        "---",
        "",
        "*Report generated by SafeHome MCP. Data sourced from Census Geocoder, "
        "FEMA Open API, and National Weather Service. Not a substitute for "
        "official flood zone maps or professional inspections.*",
    ]
    return "\n".join(lines)


def _severity_badge(alerts: list) -> str:
    """Generate a severity summary badge."""
    if not alerts:
        return "✅ **Weather**: No active alerts. Conditions are clear."

    # Count by severity
    counts = {}
    for a in alerts:
        sev = a.get("severity", "Unknown")
        counts[sev] = counts.get(sev, 0) + 1

    parts = []
    for sev in ["Extreme", "Severe", "Moderate", "Minor"]:
        if counts.get(sev):
            parts.append(f"{sev}: {counts[sev]}")
    if parts:
        return f"🚨 **Weather**: {', '.join(parts)} — check alerts below."
    return f"⚠️ **Weather**: {len(alerts)} alert(s) active — review details below."


def _disaster_badge(summary: str) -> str:
    """Generate a FEMA disaster history badge."""
    if not summary or "No FEMA disaster declarations" in summary:
        return "✅ **Disasters**: No recent disaster declarations for this county."
    if "no disasters recorded" in summary.lower():
        return "✅ **Disasters**: No recent disaster declarations."
    return "⚠️ **Disasters**: This county has recorded disasters. Review history below."


def _extract_state(formatted_address: str, county: str | None) -> str | None:
    """Extract the 2-letter state code from a formatted address or county string."""
    if county:
        # Try to find a state code in the county string (e.g. "Somewhere, XX")
        for part in county.split(","):
            part = part.strip()
            code = get_state_code(part)
            if code and len(part) == 2:
                return code

    if formatted_address:
        # Census format: "1600 PENNSYLVANIA AVE NW, WASHINGTON, DC, 20500"
        parts = [p.strip() for p in formatted_address.split(",")]
        for part in parts:
            code = get_state_code(part)
            if code and len(part) == 2:
                return code
            # Also try full name
            code = get_state_code(part)
            if code:
                return code
    return None