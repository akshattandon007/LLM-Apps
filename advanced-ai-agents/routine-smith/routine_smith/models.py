"""Data models for RoutineSmith — Daily Routine Optimizer & Habit Architect."""

from dataclasses import dataclass, field
from datetime import time, date, datetime
from enum import Enum
from typing import Optional


class EnergyPattern(Enum):
    MORNING = "morning"
    NIGHT = "night"
    BALANCED = "balanced"


class GoalCategory(Enum):
    FITNESS = "fitness"
    LEARNING = "learning"
    NUTRITION = "nutrition"
    MINDFULNESS = "mindfulness"
    PRODUCTIVITY = "productivity"
    SOCIAL = "social"
    CREATIVE = "creative"
    SLEEP = "sleep"
    FINANCE = "finance"
    OTHER = "other"


class TaskEnergyLevel(Enum):
    HIGH = "high"       # Deep work, focused thinking, intense exercise
    MEDIUM = "medium"   # Reading, planning, light exercise, chores
    LOW = "low"         # Habits, routines, passive learning, winding down


class Urgency(Enum):
    CRITICAL = "critical"   # Safety, health, deadlines
    IMPORTANT = "important" # Goals, commitments
    NICE = "nice"           # Aspirational, when time permits
    FLEXIBLE = "flexible"   # Can be dropped any day


@dataclass
class TimePocket:
    """A block of available time in the day."""
    label: str
    start: time
    end: time
    duration_minutes: int
    typical_energy: EnergyPattern
    is_commute_linked: bool = False
    is_mealtime_linked: bool = False


@dataclass
class Goal:
    """A user goal to be translated into routine tasks."""
    description: str
    category: GoalCategory
    frequency: str  # "daily", "weekly_N" (e.g. "weekly_3"), "weekdays", "weekends"
    duration_per_session_minutes: int
    energy_required: TaskEnergyLevel
    urgency: Urgency = Urgency.NICE
    cue_trigger: Optional[str] = None  # Existing habit to piggyback on
    notes: str = ""


@dataclass
class RoutineTask:
    """A concrete task placed in the daily schedule."""
    label: str
    goal_ref: Optional[str]  # References the goal description
    start_time: time
    duration_minutes: int
    energy_level: TaskEnergyLevel
    category: GoalCategory
    is_habit_stack: bool = False
    cue_trigger: Optional[str] = None
    completed: bool = False
    notes: str = ""


@dataclass
class UserProfile:
    """The user's schedule profile and preferences."""
    wake_time: time = time(7, 0)
    sleep_time: time = time(23, 0)
    commute_minutes: int = 30
    work_start: Optional[time] = time(9, 0)
    work_end: Optional[time] = time(17, 0)
    has_flexible_schedule: bool = False
    energy_pattern: EnergyPattern = EnergyPattern.BALANCED
    morning_routine_minutes: int = 30
    evening_routine_minutes: int = 45
    meal_prep_minutes: int = 60
    exercise_minutes_target: int = 30
    goals: list[Goal] = field(default_factory=list)
    time_pockets: list[TimePocket] = field(default_factory=list)


@dataclass
class DailyRoutine:
    """A complete daily routine generated by the orchestrator."""
    date: str  # ISO date string
    tasks: list[RoutineTask] = field(default_factory=list)
    total_used_minutes: int = 0
    total_available_minutes: int = 0
    score: float = 0.0  # 0-100 health/balance score
    vetoes: list[str] = field(default_factory=list)  # Record of agent vetoes
    adjustments: list[str] = field(default_factory=list)

    @property
    def completion_rate(self) -> float:
        if not self.tasks:
            return 0.0
        return sum(1 for t in self.tasks if t.completed) / len(self.tasks)


@dataclass
class AgentMessage:
    """A message from one agent to another during negotiation."""
    sender: str
    recipient: str
    message_type: str  # "proposal", "veto", "adjustment", "info"
    content: str
    related_task: Optional[str] = None