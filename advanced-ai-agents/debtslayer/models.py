"""Data models for DebtSlayer."""

from __future__ import annotations
import json
from dataclasses import dataclass, field, asdict
from typing import Optional
from datetime import datetime, date, timezone


@dataclass
class Debt:
    """A single debt account."""
    label: str
    balance: float
    apr: float  # annual percentage rate (e.g. 22.99 for 22.99%)
    min_payment: float  # minimum monthly payment in dollars

    @property
    def monthly_interest(self) -> float:
        """Monthly interest cost."""
        return self.balance * (self.apr / 100.0 / 12.0)

    @property
    def apr_display(self) -> str:
        return f"{self.apr:.2f}%"

    def __post_init__(self):
        assert self.balance >= 0, f"Debt '{self.label}' balance must be >= 0"
        assert self.apr >= 0, f"Debt '{self.label}' APR must be >= 0"
        assert self.min_payment >= 0, f"Debt '{self.label}' min_payment must be >= 0"

    def to_json(self) -> dict:
        return asdict(self)

    @classmethod
    def from_json(cls, d: dict) -> "Debt":
        return cls(**d)


@dataclass
class PayoffPlan:
    """A complete payoff plan with timeline."""
    debts: list[Debt]
    monthly_surplus: float  # extra money available beyond minimums
    method: str  # "avalanche" or "snowball"
    months_to_payoff: int
    total_interest: float
    payment_schedule: list[dict] = field(default_factory=list)
    generated_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_json(self) -> dict:
        return {
            "debts": [d.to_json() for d in self.debts],
            "monthly_surplus": self.monthly_surplus,
            "method": self.method,
            "months_to_payoff": self.months_to_payoff,
            "total_interest": round(self.total_interest, 2),
            "generated_at": self.generated_at,
        }


@dataclass
class SpendingProfile:
    """User's monthly income and expenses."""
    income: float
    expenses: float

    @property
    def surplus(self) -> float:
        return max(0.0, self.income - self.expenses)

    @property
    def deficit(self) -> bool:
        return self.income < self.expenses


@dataclass
class CreditorLetter:
    """A drafted creditor negotiation letter."""
    creditor_name: str
    balance: float
    apr: float
    hardship_reason: str
    body: str
    generated_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_text(self) -> str:
        today = date.today().strftime("%B %d, %Y")
        return f"""Date: {today}

Re: Debt Negotiation Request — {self.creditor_name} Account

To whom it may concern at {self.creditor_name},

{self.body}

Sincerely,
[Your Name]

---
Generated by DebtSlayer on {self.generated_at}
"""